        AssertContains(generated.Source,
                       "{.name = \"cooldown\", .type = {.kind = Fenrir::Kind::Optional, .element = &Test_Table_cooldown_Element, " +
                       ".optional = &Fenrir::OptionalOperationsOf<decltype(Test::Table::cooldown)::value_type>}}",
