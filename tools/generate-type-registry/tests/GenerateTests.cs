using System.Runtime.CompilerServices;
using Xunit;

namespace GenerateTypeRegistry.Tests;

public sealed class GenerateTests
{
    private static string RepositoryDirectory([CallerFilePath] string here = "") =>
        Path.GetFullPath(Path.Combine(Path.GetDirectoryName(here)!, "..", "..", ".."));

    // describe-api's fixture: one of everything a description records, and its committed description.
    private static string FixtureSelection =>
        Path.Combine(RepositoryDirectory(), "tools", "describe-api", "tests", "Fixture", "Fixture.api.toml");

    [Fact]
    public void TheFixtureGivesTheCommittedHeaderAndSourceByteForByte()
    {
        var registration = Registration.Read(FixtureSelection);
        Assert.True(registration is not null, "The fixture's selection should have a [registration] table.");

        var generated = Generator.Generate(registration, File.ReadAllText(registration.DescriptionPath),
                                           skipUnsupported: true);

        var committedHeader = File.ReadAllText(registration.HeaderPath);
        Assert.True(committedHeader == generated.Header,
                    "The fixture's registration header differs from the committed one. If the change is meant, " +
                    "regenerate it (the fenrir-generate-type-registry target) and review the diff.\n" +
                    FirstDifference(committedHeader, generated.Header));
        var committedSource = File.ReadAllText(registration.SourcePath);
        Assert.True(committedSource == generated.Source,
                    "The fixture's registration source differs from the committed one. If the change is meant, " +
                    "regenerate it (the fenrir-generate-type-registry target) and review the diff.\n" +
                    FirstDifference(committedSource, generated.Source));
    }

    [Fact]
    public void TheGeneratedFilesStartWithTheGeneratedLineAndHaveOnlyLineFeeds()
    {
        var registration = Registration.Read(FixtureSelection)!;
        var generated = Generator.Generate(registration, File.ReadAllText(registration.DescriptionPath),
                                           skipUnsupported: true);

        foreach (var text in new[] { generated.Header, generated.Source })
        {
            Assert.True(text.StartsWith("// Generated by tools/generate-type-registry from Fixture.api.json. Do not edit.\n",
                                        StringComparison.Ordinal),
                        "A generated file's first line should say what generated it and not to edit it.");
            Assert.False(text.Contains('\r'), "A generated file should have LF line ends on every platform.");
            Assert.True(text.EndsWith('\n'), "A generated file should end with a line feed.");
        }
    }

    [Fact]
    public void RunningTwiceOnAnUnchangedDescriptionRewritesNothing()
    {
        using var directory = new TemporaryDirectory();
        var selection = WriteRegisteredSelection(directory, File.ReadAllText(
            Path.Combine(Path.GetDirectoryName(FixtureSelection)!, "Fixture.api.json")));
        var header = Path.Combine(directory.Path, "include", "Fixture", "Generated", "FixtureTypes.hpp");
        var source = Path.Combine(directory.Path, "src", "Generated", "FixtureTypes.cpp");

        Assert.True(Program.Main([selection, "--skip-unsupported"]) == 0, "The first run should write the registration.");
        var earlier = DateTime.UtcNow.AddHours(-1);
        File.SetLastWriteTimeUtc(header, earlier);
        File.SetLastWriteTimeUtc(source, earlier);
        Assert.True(Program.Main([selection, "--skip-unsupported"]) == 0, "The second run should succeed.");

        Assert.True(File.GetLastWriteTimeUtc(header) == earlier, "A second run rewrote the unchanged header.");
        Assert.True(File.GetLastWriteTimeUtc(source) == earlier, "A second run rewrote the unchanged source.");
    }

    [Fact]
    public void TheSourceIncludesTheHeaderByItsPathFromTheSource()
    {
        using var directory = new TemporaryDirectory();
        var selection = WriteRegisteredSelection(directory, Description(Type("Test::Plain", "struct", "component",
                                                                              Field("value", "\"kind\": \"i32\""))));

        var registration = Registration.Read(selection)!;
        var generated = Generator.Generate(registration, File.ReadAllText(registration.DescriptionPath), false);

        Assert.True(generated.Source.Contains("#include \"../../include/Fixture/Generated/FixtureTypes.hpp\"\n",
                                              StringComparison.Ordinal),
                    "The source should include its header by the header's path relative to the source.");
        Assert.True(generated.Header.Contains("#include \"Fixture.hpp\"\n", StringComparison.Ordinal),
                    "The header should include each of [registration] includes, as spelled.");
    }

    [Fact]
    public void ASelectionWithoutARegistrationTableWritesNothing()
    {
        using var directory = new TemporaryDirectory();
        var selection = Path.Combine(directory.Path, "Fixture.api.toml");
        File.WriteAllText(selection, "headers = [\"Fixture.hpp\"]\n\n[types]\n\"Test::Plain\" = \"component\"\n");

        Assert.True(Registration.Read(selection) is null, "A selection without [registration] has no registration.");
        Assert.True(Program.Main([selection]) == 0, "A package without a registration is not an error.");
        Assert.True(Directory.GetFileSystemEntries(directory.Path).Length == 1, "Nothing should have been written.");
    }

    [Theory]
    [InlineData("\"kind\": \"quaternion\"", "Test::Odd::value: its kind 'quaternion' is not one generate-type-registry knows")]
    [InlineData("\"kind\": \"array\", \"elementKind\": \"tensor\", \"length\": 2",
                "Test::Odd::value: its element kind 'tensor' is not one generate-type-registry knows")]
    [InlineData("\"kind\": \"string\"",
                "Test::Odd::value: a string in a fixed-layout type, which is visited by offset (ticket 06 generates " +
                "visitors for the owning kinds)")]
    public void AFieldOfAKindTheToolDoesNotKnowFailsNamingTheTypeAndField(string kind, string diagnostic)
    {
        var description = Description(Type("Test::Odd", "struct", "component", Field("value", kind)));

        AssertFails(description, diagnostic, skipUnsupported: true);
    }

    [Fact]
    public void ATypeOfARoleTheToolDoesNotKnowFailsNamingTheType()
    {
        var description = Description(Type("Test::Odd", "struct", "widget", Field("value", "\"kind\": \"i32\"")));

        AssertFails(description, "Test::Odd: its role 'widget' is not one generate-type-registry knows",
                    skipUnsupported: true);
    }

    [Fact]
    public void ATypeOfACategoryTheToolDoesNotKnowFailsNamingTheType()
    {
        var description = Description(Type("Test::Odd", "variant", "component", Field("value", "\"kind\": \"i32\"")));

        AssertFails(description, "Test::Odd: its category 'variant' is not one generate-type-registry knows",
                    skipUnsupported: true);
    }

    [Theory]
    [InlineData("data-asset", "Test::Owned: a data asset is visited by member, by a generated function ticket 06 writes")]
    [InlineData("settings", "Test::Owned: a settings type is visited by member, by a generated function ticket 06 writes")]
    public void ADataAssetOrSettingsTypeFailsUntilTicket06(string role, string diagnostic)
    {
        var description = Description(TypeWithoutLayout("Test::Owned", role, Field("name", "\"kind\": \"string\"")));

        AssertFails(description, diagnostic, skipUnsupported: false);
    }

    [Fact]
    public void SkippingUnsupportedTypesLeavesOutByMemberTypesAndWhatHoldsThem()
    {
        var description = Description(
            TypeWithoutLayout("Test::Row", "nested", Field("name", "\"kind\": \"string\"")),
            TypeWithoutLayout("Test::Table", "data-asset", Field("rows", "\"kind\": \"list\", \"elementKind\": \"struct\", \"elementType\": \"Test::Row\"")),
            Type("Test::Plain", "struct", "component", Field("value", "\"kind\": \"i32\"")));
        using var directory = new TemporaryDirectory();
        var registration = Registration.Read(WriteRegisteredSelection(directory, description))!;

        var generated = Generator.Generate(registration, description, skipUnsupported: true);

        Assert.True(generated.Header.Contains("Fenrir::Describe<Test::Plain>", StringComparison.Ordinal),
                    "A fixed-layout type should still be described.");
        Assert.False(generated.Header.Contains("Test::Row", StringComparison.Ordinal) ||
                     generated.Header.Contains("Test::Table", StringComparison.Ordinal),
                     "Skipped types should have no Describe<T>.");
        Assert.False(generated.Source.Contains("Test::Row", StringComparison.Ordinal) ||
                     generated.Source.Contains("Test::Table", StringComparison.Ordinal),
                     "Skipped types should have no description.");
    }

    [Fact]
    public void AFailedRunWritesNothing()
    {
        using var directory = new TemporaryDirectory();
        var selection = WriteRegisteredSelection(directory, Description(Type("Test::Odd", "struct", "component",
                                                                             Field("value", "\"kind\": \"quaternion\""))));

        Assert.True(Program.Main([selection]) == 1, "A description the tool cannot generate from should fail it.");
        Assert.False(Directory.Exists(Path.Combine(directory.Path, "include")) ||
                     Directory.Exists(Path.Combine(directory.Path, "src")),
                     "A failed run should write no header or source.");
    }

    [Theory]
    [InlineData("header = \"a.hpp\"\nsource = \"a.cpp\"\nincludes = []\n",
                "[registration] 'function' is the qualified name of the registration function")]
    [InlineData("header = \"a.hpp\"\nsource = \"a.cpp\"\nfunction = \"Register Types\"\nincludes = []\n",
                "[registration] 'function' is the qualified name of the registration function")]
    [InlineData("source = \"a.cpp\"\nfunction = \"F\"\nincludes = []\n", "[registration] 'header' is the path of the generated header")]
    [InlineData("header = \"a.hpp\"\nfunction = \"F\"\nincludes = []\n", "[registration] 'source' is the path of the generated source")]
    [InlineData("header = \"a.hpp\"\nsource = \"a.cpp\"\nfunction = \"F\"\n",
                "[registration] 'includes' is a list of the headers declaring the described types")]
    [InlineData("header = \"a.hpp\"\nsource = \"a.cpp\"\nfunction = \"F\"\nincludes = []\nextra = 1\n",
                "[registration] has an unknown key 'extra' (it has 'header', 'source', 'function' and 'includes')")]
    public void AMalformedRegistrationTableFailsSayingWhatIsWrong(string table, string diagnostic)
    {
        using var directory = new TemporaryDirectory();
        var selection = Path.Combine(directory.Path, "Fixture.api.toml");
        File.WriteAllText(selection, "headers = [\"Fixture.hpp\"]\n\n[types]\n\"Test::Plain\" = \"component\"\n\n" +
                                     "[registration]\n" + table);

        var exception = Assert.Throws<GenerateException>(() => Registration.Read(selection));

        Assert.True(exception.Message.Contains(diagnostic, StringComparison.Ordinal),
                    $"Reading the selection should fail with\n  {diagnostic}\nbut failed with\n  {exception.Message}");
    }

    private static void AssertFails(string description, string diagnostic, bool skipUnsupported)
    {
        using var directory = new TemporaryDirectory();
        var registration = Registration.Read(WriteRegisteredSelection(directory, description))!;

        var exception = Assert.Throws<GenerateException>(() => Generator.Generate(registration, description, skipUnsupported));

        Assert.True(exception.Message.Contains(diagnostic, StringComparison.Ordinal),
                    $"Generating should fail with\n  {diagnostic}\nbut failed with\n  {exception.Message}");
    }

    // A selection named Fixture.api.toml in the directory, its description beside it, registering into include/ and src/.
    private static string WriteRegisteredSelection(TemporaryDirectory directory, string description)
    {
        var selection = Path.Combine(directory.Path, "Fixture.api.toml");
        File.WriteAllText(selection,
                          "headers = [\"Fixture.hpp\"]\n\n[types]\n\"Test::Plain\" = \"component\"\n\n" +
                          "[registration]\n" +
                          "header = \"include/Fixture/Generated/FixtureTypes.hpp\"\n" +
                          "source = \"src/Generated/FixtureTypes.cpp\"\n" +
                          "function = \"Fenrir::Generated::RegisterFixtureTypes\"\n" +
                          "includes = [\"Fixture.hpp\"]\n");
        File.WriteAllText(Path.Combine(directory.Path, "Fixture.api.json"), description);
        return selection;
    }

    private static string Description(params string[] types) =>
        "{\n  \"package\": \"Fixture\",\n  \"pointerSize\": 8,\n  \"alignment\": \"natural\",\n  \"types\": [\n" +
        string.Join(",\n", types) + "\n  ]\n}\n";

    private static string Type(string name, string category, string role, params string[] fields) =>
        $"{{\"name\": \"{name}\", \"category\": \"{category}\", \"role\": \"{role}\", \"size\": 4, \"alignment\": 4, " +
        $"\"fields\": [{string.Join(", ", fields)}]}}";

    private static string TypeWithoutLayout(string name, string role, params string[] fields) =>
        $"{{\"name\": \"{name}\", \"category\": \"struct\", \"role\": \"{role}\", \"fields\": [{string.Join(", ", fields)}]}}";

    private static string Field(string name, string kind) =>
        $"{{\"name\": \"{name}\", \"offset\": 0, {kind}, \"default\": 0}}";

    private static string FirstDifference(string expected, string actual)
    {
        var expectedLines = expected.Split('\n');
        var actualLines = actual.Split('\n');
        for (var i = 0; i < Math.Max(expectedLines.Length, actualLines.Length); ++i)
        {
            var e = i < expectedLines.Length ? expectedLines[i] : "<end>";
            var a = i < actualLines.Length ? actualLines[i] : "<end>";
            if (e != a)
            {
                return $"First difference at line {i + 1}:\n  committed: {e}\n  generated: {a}";
            }
        }

        return "The texts differ only in line endings or encoding.";
    }

    private sealed class TemporaryDirectory : IDisposable
    {
        public TemporaryDirectory()
        {
            Path = System.IO.Path.Combine(System.IO.Path.GetTempPath(), "generate-type-registry-" + Guid.NewGuid().ToString("N"));
            Directory.CreateDirectory(Path);
        }

        public string Path { get; }

        public void Dispose() => Directory.Delete(Path, recursive: true);
    }
}
