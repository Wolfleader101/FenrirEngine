    // The registration a description gives, skipping nothing.
    private static GeneratedFiles Generate(string description)
    {
        using var directory = new TemporaryDirectory();
        var registration = Registration.Read(WriteRegisteredSelection(directory, description))!;
        return Generator.Generate(registration, description, skipUnsupported: false);
    }

    private static void AssertContains(string text, string expected, string why) =>
        Assert.True(text.Contains(expected, StringComparison.Ordinal), $"{why}\nExpected to find:\n{expected}\nin:\n{text}");

    private static void AssertFails(string description, string diagnostic, bool skipUnsupported)
    {
        using var directory = new TemporaryDirectory();
        var registration = Registration.Read(WriteRegisteredSelection(directory, description))!;

        var exception = Assert.Throws<GenerateException>(() => Generator.Generate(registration, description, skipUnsupported));

        Assert.True(exception.Message.Contains(diagnostic, StringComparison.Ordinal),
                    $"Generating should fail with\n  {diagnostic}\nbut failed with\n  {exception.Message}");
    }

    // A selection named Fixture.api.toml in the directory, its description beside it, registering into include/ and src/.
    private static string WriteRegisteredSelection(TemporaryDirectory directory, string description)
    {
        var selection = Path.Combine(directory.Path, "Fixture.api.toml");
        File.WriteAllText(selection,
                          "headers = [\"Fixture.hpp\"]\n\n[types]\n\"Test::Plain\" = \"component\"\n\n" +
                          "[registration]\n" +
                          "header = \"include/Fixture/Generated/FixtureTypes.hpp\"\n" +
                          "source = \"src/Generated/FixtureTypes.cpp\"\n" +
                          "function = \"Fenrir::Generated::RegisterFixtureTypes\"\n" +
                          "includes = [\"Fixture.hpp\"]\n");
        File.WriteAllText(Path.Combine(directory.Path, "Fixture.api.json"), description);
        return selection;
    }

    private static string Description(params string[] types) =>
        "{\n  \"package\": \"Fixture\",\n  \"pointerSize\": 8,\n  \"alignment\": \"natural\",\n  \"types\": [\n" +
        string.Join(",\n", types) + "\n  ]\n}\n";

    private static string Type(string name, string category, string role, params string[] fields) =>
        $"{{\"name\": \"{name}\", \"category\": \"{category}\", \"role\": \"{role}\", \"size\": 4, \"alignment\": 4, " +
        $"\"fields\": [{string.Join(", ", fields)}]}}";

    private static string TypeWithoutLayout(string name, string role, params string[] fields) =>
        $"{{\"name\": \"{name}\", \"category\": \"struct\", \"role\": \"{role}\", \"fields\": [{string.Join(", ", fields)}]}}";

    // A data asset extending another, by member as every data asset is.
    private static string DerivedType(string name, string baseName, params string[] fields) =>
        $"{{\"name\": \"{name}\", \"category\": \"struct\", \"role\": \"data-asset\", \"base\": \"{baseName}\", " +
        $"\"fields\": [{string.Join(", ", fields)}]}}";

    // A tagged union of one kind, in the shape describe-api records one.
    private static string TaggedUnion(string name) =>
        $"{{\"name\": \"{name}\", \"category\": \"tagged-union\", \"role\": \"nested\", \"size\": 8, \"alignment\": 4, " +
        "\"tag\": {\"name\": \"m_type\", \"offset\": 0, \"kind\": \"u8\", \"default\": 0}, \"unionOffset\": 4, " +
        "\"kinds\": [{\"name\": \"m_radius\", \"tag\": \"Sphere\", \"kind\": \"f32\"}], \"defaultKind\": \"m_radius\"}";

    private static string Field(string name, string kind) =>
        $"{{\"name\": \"{name}\", \"offset\": 0, {kind}, \"default\": 0}}";

    private static string FirstDifference(string expected, string actual)
    {
        var expectedLines = expected.Split('\n');
        var actualLines = actual.Split('\n');
        for (var i = 0; i < Math.Max(expectedLines.Length, actualLines.Length); ++i)
        {
            var e = i < expectedLines.Length ? expectedLines[i] : "<end>";
            var a = i < actualLines.Length ? actualLines[i] : "<end>";
            if (e != a)
            {
                return $"First difference at line {i + 1}:\n  committed: {e}\n  generated: {a}";
            }
        }

        return "The texts differ only in line endings or encoding.";
    }

    private sealed class TemporaryDirectory : IDisposable
    {
        public TemporaryDirectory()
        {
            Path = System.IO.Path.Combine(System.IO.Path.GetTempPath(), "generate-type-registry-" + Guid.NewGuid().ToString("N"));
            Directory.CreateDirectory(Path);
        }

        public string Path { get; }

        public void Dispose() => Directory.Delete(Path, recursive: true);
    }
