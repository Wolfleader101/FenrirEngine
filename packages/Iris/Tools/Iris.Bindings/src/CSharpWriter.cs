using System.Text;

namespace Iris.Bindings;

/// <summary>
/// Writes the C# side: one mirror per struct, tagged union and enum, the natives' declarations, and the defaults test's
/// C# class.
/// </summary>
internal static class CSharpWriter
{
    private const int Width = 120;

    /// <summary>Each mirror's file name (<c>&lt;Type&gt;.cs</c>) and text.</summary>
    public static IEnumerable<KeyValuePair<string, string>> Mirrors(Binding binding) =>
        binding.Mirrored.Select(type => KeyValuePair.Create(binding.CSharpName(type) + ".cs", Mirror(binding, type)));

    private static string Mirror(Binding binding, DescribedType type)
    {
        var text = new Writer();
        text.Line($"// Generated by Iris.Bindings from {type.Name} ({Path.GetFileName(type.Source)}): do not edit.");
        text.Line("// Change the C++ header, then regenerate its description and this binding.");
        text.Line();

        var usings = new List<string>();
        if (type.Category == Category.TaggedUnion)
        {
            usings.Add("System.Runtime.InteropServices");
        }

        if (type.Fields.Any(field => field.Kind.IsArray && !binding.IsFixedBuffer(type, field)))
        {
            usings.Add("System.Runtime.CompilerServices");
        }

        usings.Sort(StringComparer.Ordinal);
        if (type.Category != Category.Enum)
        {
            usings.AddRange(binding.Config.CSharp.Usings);
            // The namespaces of the types it holds that a binding it uses mirrors.
            usings.AddRange(binding.UsedNamespaces(Binding.Named(type)).Where(space => !usings.Contains(space)));
        }

        foreach (var name in usings)
        {
            text.Line($"using {name};");
        }

        if (usings.Count > 0)
        {
            text.Line();
        }

        text.Line($"namespace {binding.Config.Namespace};");
        text.Line();
        if (type.Fields.Any(field => binding.IsPrivate(type, field)))
        {
            // Native code reads and writes a private field, which the compiler cannot see.
            text.Line("#pragma warning disable CS0169, CS0414, CS0649");
            text.Line();
        }

        Doc(text, type.Doc);
        if (type.Category == Category.Enum)
        {
            Enum(binding, type, text);
        }
        else
        {
            Struct(binding, type, text);
        }

        return text.ToString();
    }

    private static void Enum(Binding binding, DescribedType type, Writer text)
    {
        text.Line($"public enum {binding.CSharpName(type)} : {Binding.CSharpScalar(type.Underlying!)}");
        text.Line("{");
        text.Indent();
        foreach (var value in type.Values)
        {
            Doc(text, value.Doc);
            text.Line($"{binding.MemberName(type, value.Name)} = {value.Value},");
        }

        text.Outdent();
        text.Line("}");
    }

    private static void Struct(Binding binding, DescribedType type, Writer text)
    {
        var config = binding.Config.CSharp;
        var name = binding.CSharpName(type);
        var interfaces = new List<string>();
        var readOnly = binding.IsReadOnly(type);
        switch (type.Role)
        {
            case Role.Component:
                text.Line($"[{config.ComponentAttribute}(\"{binding.RegisteredName(type)}\")]");
                interfaces.Add(binding.Config.Registration?.ReadOnly.Contains(type.Name) == true
                                   ? config.ReadOnlyComponentInterface
                                   : config.ComponentInterface);
                break;
            case Role.Event:
                text.Line($"[{config.EventAttribute}(\"{binding.RegisteredName(type)}\")]");
                interfaces.Add(config.EventInterface);
                break;
            case Role.SceneResource or Role.AppResource:
                text.Line($"[{config.ResourceAttribute}(\"{binding.RegisteredName(type)}\")]");
                interfaces.Add(binding.IsRegisteredReadOnly(type) ? config.ReadOnlyResourceInterface! : config.ResourceInterface!);
                break;
        }

        if (type.Category == Category.TaggedUnion)
        {
            text.Line(binding.Config.Nouns.TryGetValue(type.Name, out var noun)
                          ? $"[{config.TaggedUnionAttribute}(Noun = \"{noun}\")]"
                          : $"[{config.TaggedUnionAttribute}]");
            text.Line("[StructLayout(LayoutKind.Explicit)]");
        }

        // A fixed buffer needs an unsafe context.
        var unsafeType = type.Fields.Any(field => binding.IsFixedBuffer(type, field)) ? "unsafe " : "";
        var access = binding.IsInternal(type) ? "internal" : "public";
        var modifiers = readOnly ? $"{access} readonly {unsafeType}partial struct" : $"{access} {unsafeType}partial struct";
        text.Line(interfaces.Count == 0 ? $"{modifiers} {name}" : $"{modifiers} {name} : {string.Join(", ", interfaces)}");
        text.Line("{");
        text.Indent();
        if (type.Category == Category.TaggedUnion)
        {
            // The storage only: the SDK's tagged-union generator writes the constructor, the views and the conversions.
            var tag = type.Tag!;
            text.Line($"[FieldOffset({tag.Offset})] private {binding.CSharpType(tag.Kind.Kind, tag.Kind.Type)} {Binding.TagFieldName};");
            foreach (var kind in type.Kinds)
            {
                Doc(text, kind.Doc);
                text.Line($"[FieldOffset({type.UnionOffset})] private {binding.CSharpType(kind.Kind.Kind, kind.Kind.Type)} " +
                          $"{binding.KindFieldName(type, kind)};");
            }
        }
        else
        {
            Fields(binding, type, name, readOnly, text);
        }

        text.Outdent();
        text.Line("}");
    }

    private static void Fields(Binding binding, DescribedType type, string name, bool readOnly, Writer text)
    {
        // With every default zero, `default` holds them, so the mirror has no initialisers and no constructor to run them.
        var initialised = binding.NeedsConstructor(type);
        foreach (var member in type.Fields)
        {
            var memberName = binding.MemberName(type, member.Name);
            var access = binding.IsPrivate(type, member) ? "private" : "public";
            // A field holding a read-only struct is read-only too, so C# cannot write the struct whole.
            var field = readOnly || (member.Kind.Kind == "struct" && binding.IsReadOnly(binding.Type(member.Kind.Type!)))
                            ? $"{access} readonly"
                            : access;
            Doc(text, member.Doc);
            if (binding.IsFixedBuffer(type, member))
            {
                text.Line($"{field} fixed {binding.CSharpType(member.Kind.ElementKind!, null)} {memberName}[{member.Kind.Length}];");
            }
            else if (member.Kind.IsArray)
            {
                text.Line($"{field} {Binding.ArrayTypeName(memberName)} {memberName};");
            }
            else if (initialised)
            {
                var value = binding.Default(member.Kind.Kind, member.Kind.Type, member.Default, member.Name);
                text.Line($"{field} {binding.CSharpType(member.Kind.Kind, member.Kind.Type)} {memberName} = {value};");
            }
            else
            {
                text.Line($"{field} {binding.CSharpType(member.Kind.Kind, member.Kind.Type)} {memberName};");
            }
        }

        if (initialised)
        {
            text.Line();

            // Explicit, so `new T()` runs the initialisers; an array's elements are set here, since C# cannot initialise
            // one.
            text.Line($"public {name}()");
            text.Line("{");
            text.Indent();
            foreach (var member in type.Fields.Where(member => member.Kind.IsArray))
            {
                var memberName = binding.MemberName(type, member.Name);
                var index = 0;
                foreach (var element in member.Default.EnumerateArray())
                {
                    text.Line($"{memberName}[{index}] = {binding.ElementDefault(member.Kind, element, member.Name)};");
                    index++;
                }
            }

            text.Outdent();
            text.Line("}");
        }

        foreach (var member in type.Fields.Where(member => member.Kind.IsArray && !binding.IsFixedBuffer(type, member)))
        {
            var memberName = binding.MemberName(type, member.Name);
            text.Line();
            text.Line($"/// <summary>The storage of <see cref=\"{memberName}\"/>: <see cref=\"Length\"/> elements.</summary>");
            text.Line($"[InlineArray({member.Kind.Length})]");
            text.Line($"public struct {Binding.ArrayTypeName(memberName)}");
            text.Line("{");
            text.Indent();
            text.Line("/// <summary>How many elements it holds: the C++ array's length.</summary>");
            text.Line($"public const int Length = {member.Kind.Length};");
            text.Line();
            text.Line($"private {binding.CSharpType(member.Kind.ElementKind!, member.Kind.ElementType)} _element;");
            text.Outdent();
            text.Line("}");
        }
    }

    /// <summary>The defaults test's C# class: one static method per registered type, returning its <c>new T()</c>.</summary>
    public static string Defaults(Binding binding, TestsConfig tests, string cppTestName)
    {
        var dot = tests.Class.LastIndexOf('.');
        var text = new Writer();
        text.Line($"// Generated by Iris.Bindings from {Path.GetFileName(binding.Config.Path)}: do not edit.");
        text.Line();
        if (dot > 0)
        {
            text.Line($"namespace {tests.Class[..dot]};");
            text.Line();
        }

        Doc(text, $"C#'s new value of each type the binding registers. The generated {cppTestName} calls each method " +
                  "and compares its value with C++'s T{} field by field, through the type's mapping.");
        text.Line($"public static class {tests.Class[(dot + 1)..]}");
        text.Line("{");
        text.Indent();
        foreach (var type in binding.Registered)
        {
            text.Line($"public static global::{binding.QualifiedName(type)} {binding.CSharpName(type)}() => new();");
        }

        text.Outdent();
        text.Line("}");
        return text.ToString();
    }

    /// <summary>
    /// The native functions' C# declarations: one <c>internal static unsafe partial class</c> of
    /// <c>[NativeFunction] public static partial</c> methods, in the description's order, each documented from its C++
    /// doc comment. The SDK's generator writes their bodies and the fields the host binds.
    /// </summary>
    public static KeyValuePair<string, string> Natives(Binding binding, NativesDescription natives,
                                                       IReadOnlyList<BoundNative> bound)
    {
        var config = binding.Config.Natives!;
        var text = new Writer();
        text.Line($"// Generated by Iris.Bindings from {Path.GetFileName(natives.Path)}: do not edit.");
        text.Line("// Change the native functions' C++ definitions, then regenerate their description and this binding.");
        text.Line();
        // System for ReadOnlySpan<char>, when a native takes text.
        var usings = NativesUsings(binding, bound, bound.Any(native => native.TakesText) ? ["System"] : []);
        foreach (var name in usings)
        {
            text.Line($"using {name};");
        }

        if (usings.Count > 0)
        {
            text.Line();
        }

        var sources = string.Join(", ", natives.Functions.Select(function => function.Source).Distinct());
        text.Line($"namespace {binding.Config.Namespace};");
        text.Line();
        Doc(text, $"The native functions of the {binding.Config.Name} binding, each registered as " +
                  $"\"{binding.Config.Namespace}.{config.Class}.<Method>\" and defined by the C++ function of that name " +
                  $"({sources}).");
        text.Line($"internal static unsafe partial class {config.Class}");
        text.Line("{");
        text.Indent();
        var first = true;
        foreach (var native in bound)
        {
            if (!first)
            {
                text.Line();
            }

            first = false;
            var function = native.Function;
            Doc(text, function.Doc);
            foreach (var parameter in function.Parameters.Where(parameter => parameter.Doc != null))
            {
                Tagged(text, $"<param name=\"{parameter.Name}\">", Escape(parameter.Doc!), "</param>");
            }

            if (function.ReturnsDoc != null)
            {
                Tagged(text, "<returns>", Escape(function.ReturnsDoc), "</returns>");
            }

            text.Line($"[{config.Attribute}]");
            Signature(text, $"public static partial {native.Result} {function.Name}(", native.Parameters, ");");
        }

        text.Outdent();
        text.Line("}");
        return KeyValuePair.Create(config.Class + ".cs", text.ToString());
    }

    // The natives' usings: `first`, the configuration's, and the namespaces of the bindings it uses whose types the natives
    // name.
    private static List<string> NativesUsings(Binding binding, IReadOnlyList<BoundNative> bound, IReadOnlyList<string> first)
    {
        var usings = first.ToList();
        usings.AddRange(binding.Config.CSharp.Usings.Where(space => !usings.Contains(space)));
        usings.AddRange(binding.UsedNamespaces(bound.SelectMany(native => native.Named)).Where(space => !usings.Contains(space)));
        return usings;
    }

    // `start` and the comma-separated parts, then `end`: on one line when it fits, else broken after commas and
    // aligned under the first part.
    private static void Signature(Writer text, string start, IReadOnlyList<string> parts, string end)
    {
        var single = start + string.Join(", ", parts) + end;
        if (text.Indentation + single.Length <= Width || parts.Count < 2)
        {
            text.Line(single);
            return;
        }

        var line = new StringBuilder(start);
        var empty = true;
        for (var index = 0; index < parts.Count; index++)
        {
            var part = parts[index] + (index + 1 < parts.Count ? "," : end);
            if (!empty && text.Indentation + line.Length + 1 + part.Length > Width)
            {
                text.Line(line.ToString());
                line.Clear().Append(' ', start.Length);
                empty = true;
            }

            line.Append(empty ? "" : " ").Append(part);
            empty = false;
        }

        text.Line(line.ToString());
    }

    // An XML doc element on one line when it fits, else its text wrapped between the tags.
    private static void Tagged(Writer text, string open, string content, string close)
    {
        var width = Width - text.Indentation - "/// ".Length;
        var single = open + content + close;
        if (single.Length <= width)
        {
            text.Line($"/// {single}");
            return;
        }

        text.Line($"/// {open}");
        Wrap(text, content, width);
        text.Line($"/// {close}");
    }

    /// <summary>
    /// A doc comment: its first paragraph as the summary and the rest as remarks, XML-escaped and wrapped. Nothing is
    /// written when there is none.
    /// </summary>
    private static void Doc(Writer text, string? doc)
    {
        if (string.IsNullOrWhiteSpace(doc))
        {
            return;
        }

        var paragraphs = doc.Split("\n\n").Select(paragraph => Escape(paragraph.Trim())).ToList();
        var width = Width - text.Indentation - "/// ".Length;
        var summary = $"<summary>{paragraphs[0]}</summary>";
        if (paragraphs.Count == 1 && summary.Length <= width)
        {
            text.Line($"/// {summary}");
            return;
        }

        text.Line("/// <summary>");
        Wrap(text, paragraphs[0], width);
        text.Line("/// </summary>");
        if (paragraphs.Count > 1)
        {
            text.Line("/// <remarks>");
            for (var index = 1; index < paragraphs.Count; index++)
            {
                if (index > 1)
                {
                    text.Line("/// <para/>");
                }

                Wrap(text, paragraphs[index], width);
            }

            text.Line("/// </remarks>");
        }
    }

    // Only what XML text needs: quotes and apostrophes stay as written.
    private static string Escape(string text) => text.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");

    private static void Wrap(Writer text, string paragraph, int width)
    {
        var line = new StringBuilder();
        foreach (var word in paragraph.Split(' ', StringSplitOptions.RemoveEmptyEntries))
        {
            if (line.Length > 0 && line.Length + 1 + word.Length > width)
            {
                text.Line($"/// {line}");
                line.Clear();
            }

            if (line.Length > 0)
            {
                line.Append(' ');
            }

            line.Append(word);
        }

        if (line.Length > 0)
        {
            text.Line($"/// {line}");
        }
    }
}
