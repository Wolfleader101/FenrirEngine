using System.Text;

namespace Iris.Bindings;

/// <summary>Writes the C# side: one mirror per struct, tagged union and enum, and the defaults test's C# class.</summary>
internal static class CSharpWriter
{
    private const int Width = 120;

    /// <summary>Each mirror's file name (<c>&lt;Type&gt;.cs</c>) and text.</summary>
    public static IEnumerable<KeyValuePair<string, string>> Mirrors(Binding binding) =>
        binding.Mirrored.Select(type => KeyValuePair.Create(binding.CSharpName(type) + ".cs", Mirror(binding, type)));

    private static string Mirror(Binding binding, DescribedType type)
    {
        var text = new Writer();
        text.Line($"// Generated by Iris.Bindings from {type.Name} ({Path.GetFileName(type.Source)}): do not edit.");
        text.Line("// Change the C++ header, then regenerate its description and this binding.");
        text.Line();

        var usings = new List<string>();
        if (type.Category == Category.TaggedUnion)
        {
            usings.Add("System.Runtime.InteropServices");
        }

        if (type.Fields.Any(field => field.Kind.IsArray))
        {
            usings.Add("System.Runtime.CompilerServices");
        }

        usings.Sort(StringComparer.Ordinal);
        if (type.Category != Category.Enum)
        {
            usings.AddRange(binding.Config.CSharp.Usings);
        }

        foreach (var name in usings)
        {
            text.Line($"using {name};");
        }

        if (usings.Count > 0)
        {
            text.Line();
        }

        text.Line($"namespace {binding.Config.Namespace};");
        text.Line();
        Doc(text, type.Doc);
        if (type.Category == Category.Enum)
        {
            Enum(binding, type, text);
        }
        else
        {
            Struct(binding, type, text);
        }

        return text.ToString();
    }

    private static void Enum(Binding binding, DescribedType type, Writer text)
    {
        text.Line($"public enum {binding.CSharpName(type)} : {Binding.CSharpScalar(type.Underlying!)}");
        text.Line("{");
        text.Indent();
        foreach (var value in type.Values)
        {
            Doc(text, value.Doc);
            text.Line($"{binding.MemberName(type, value.Name)} = {value.Value},");
        }

        text.Outdent();
        text.Line("}");
    }

    private static void Struct(Binding binding, DescribedType type, Writer text)
    {
        var config = binding.Config.CSharp;
        var name = binding.CSharpName(type);
        var interfaces = new List<string>();
        var readOnly = false;
        switch (type.Role)
        {
            case Role.Component:
                text.Line($"[{config.ComponentAttribute}(\"{binding.QualifiedName(type)}\")]");
                interfaces.Add(binding.Config.Registration?.ReadOnly.Contains(type.Name) == true
                                   ? config.ReadOnlyComponentInterface
                                   : config.ComponentInterface);
                break;
            case Role.Event:
                text.Line($"[{config.EventAttribute}(\"{binding.QualifiedName(type)}\")]");
                interfaces.Add(config.EventInterface);
                readOnly = config.ReadOnlyEvents;
                break;
        }

        if (type.Category == Category.TaggedUnion)
        {
            text.Line(binding.Config.Nouns.TryGetValue(type.Name, out var noun)
                          ? $"[{config.TaggedUnionAttribute}(Noun = \"{noun}\")]"
                          : $"[{config.TaggedUnionAttribute}]");
            text.Line("[StructLayout(LayoutKind.Explicit)]");
        }

        var modifiers = readOnly ? "public readonly partial struct" : "public partial struct";
        text.Line(interfaces.Count == 0 ? $"{modifiers} {name}" : $"{modifiers} {name} : {string.Join(", ", interfaces)}");
        text.Line("{");
        text.Indent();
        if (type.Category == Category.TaggedUnion)
        {
            // The storage only: the SDK's tagged-union generator writes the constructor, the views and the conversions.
            var tag = type.Tag!;
            text.Line($"[FieldOffset({tag.Offset})] private {binding.CSharpType(tag.Kind.Kind, tag.Kind.Type)} {Binding.TagFieldName};");
            foreach (var kind in type.Kinds)
            {
                Doc(text, kind.Doc);
                text.Line($"[FieldOffset({type.UnionOffset})] private {binding.CSharpType(kind.Kind.Kind, kind.Kind.Type)} " +
                          $"{binding.KindFieldName(type, kind)};");
            }
        }
        else
        {
            Fields(binding, type, name, readOnly, text);
        }

        text.Outdent();
        text.Line("}");
    }

    private static void Fields(Binding binding, DescribedType type, string name, bool readOnly, Writer text)
    {
        var field = readOnly ? "public readonly" : "public";
        foreach (var member in type.Fields)
        {
            var memberName = binding.MemberName(type, member.Name);
            Doc(text, member.Doc);
            if (member.Kind.IsArray)
            {
                text.Line($"{field} {Binding.ArrayTypeName(memberName)} {memberName};");
            }
            else
            {
                var value = binding.Default(member.Kind.Kind, member.Kind.Type, member.Default, member.Name);
                text.Line($"{field} {binding.CSharpType(member.Kind.Kind, member.Kind.Type)} {memberName} = {value};");
            }
        }

        if (type.Fields.Count > 0)
        {
            text.Line();
        }

        // Explicit, so `new T()` runs the initialisers; an array's elements are set here, since C# cannot initialise one.
        text.Line($"public {name}()");
        text.Line("{");
        text.Indent();
        foreach (var member in type.Fields.Where(member => member.Kind.IsArray))
        {
            var memberName = binding.MemberName(type, member.Name);
            var index = 0;
            foreach (var element in member.Default.EnumerateArray())
            {
                text.Line($"{memberName}[{index}] = {binding.ElementDefault(member.Kind, element, member.Name)};");
                index++;
            }
        }

        text.Outdent();
        text.Line("}");

        foreach (var member in type.Fields.Where(member => member.Kind.IsArray))
        {
            var memberName = binding.MemberName(type, member.Name);
            text.Line();
            text.Line($"/// <summary>The storage of <see cref=\"{memberName}\"/>: {member.Kind.Length} elements.</summary>");
            text.Line($"[InlineArray({member.Kind.Length})]");
            text.Line($"public struct {Binding.ArrayTypeName(memberName)}");
            text.Line("{");
            text.Indent();
            text.Line($"private {binding.CSharpType(member.Kind.ElementKind!, member.Kind.ElementType)} _element;");
            text.Outdent();
            text.Line("}");
        }
    }

    /// <summary>The defaults test's C# class: one static method per registered type, returning its <c>new T()</c>.</summary>
    public static string Defaults(Binding binding, TestsConfig tests, string cppTestName)
    {
        var dot = tests.Class.LastIndexOf('.');
        var text = new Writer();
        text.Line($"// Generated by Iris.Bindings from {Path.GetFileName(binding.Config.Path)}: do not edit.");
        text.Line();
        if (dot > 0)
        {
            text.Line($"namespace {tests.Class[..dot]};");
            text.Line();
        }

        Doc(text, $"C#'s new value of each type the binding registers. The generated {cppTestName} calls each method " +
                  "and compares its value with C++'s T{} field by field, through the type's mapping.");
        text.Line($"public static class {tests.Class[(dot + 1)..]}");
        text.Line("{");
        text.Indent();
        foreach (var type in binding.Registered)
        {
            text.Line($"public static global::{binding.QualifiedName(type)} {binding.CSharpName(type)}() => new();");
        }

        text.Outdent();
        text.Line("}");
        return text.ToString();
    }

    /// <summary>
    /// A doc comment: its first paragraph as the summary and the rest as remarks, XML-escaped and wrapped. Nothing is
    /// written when there is none.
    /// </summary>
    private static void Doc(Writer text, string? doc)
    {
        if (string.IsNullOrWhiteSpace(doc))
        {
            return;
        }

        var paragraphs = doc.Split("\n\n").Select(paragraph => Escape(paragraph.Trim())).ToList();
        var width = Width - text.Indentation - "/// ".Length;
        var summary = $"<summary>{paragraphs[0]}</summary>";
        if (paragraphs.Count == 1 && summary.Length <= width)
        {
            text.Line($"/// {summary}");
            return;
        }

        text.Line("/// <summary>");
        Wrap(text, paragraphs[0], width);
        text.Line("/// </summary>");
        if (paragraphs.Count > 1)
        {
            text.Line("/// <remarks>");
            for (var index = 1; index < paragraphs.Count; index++)
            {
                if (index > 1)
                {
                    text.Line("/// <para/>");
                }

                Wrap(text, paragraphs[index], width);
            }

            text.Line("/// </remarks>");
        }
    }

    // Only what XML text needs: quotes and apostrophes stay as written.
    private static string Escape(string text) => text.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");

    private static void Wrap(Writer text, string paragraph, int width)
    {
        var line = new StringBuilder();
        foreach (var word in paragraph.Split(' ', StringSplitOptions.RemoveEmptyEntries))
        {
            if (line.Length > 0 && line.Length + 1 + word.Length > width)
            {
                text.Line($"/// {line}");
                line.Clear();
            }

            if (line.Length > 0)
            {
                line.Append(' ');
            }

            line.Append(word);
        }

        if (line.Length > 0)
        {
            text.Line($"/// {line}");
        }
    }
}
