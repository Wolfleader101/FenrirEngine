// FenrirShaderCompiler (ADR-0018): builds one GLSL 460 shader program into a shader container, run by
// fenrir_add_shaders (cmake/FenrirShaders.cmake). See Arguments.hpp for its options. It exits 0 when the container is
// written, 1 on a build error (each printed as file:line: error: ...), 2 on bad arguments.

#include <cstddef>
#include <cstdio>
#include <filesystem>
#include <fstream>
#include <set>
#include <string>
#include <vector>

#include "Arguments.hpp"
#include "FenrirAssets/ShaderContainer.hpp"
#include "Program.hpp"

namespace
{
    namespace fs = std::filesystem;

    bool WriteFile(const fs::path& path, const void* data, std::size_t size)
    {
        std::error_code error;
        if (path.has_parent_path())
        {
            fs::create_directories(path.parent_path(), error);
        }
        std::ofstream file(path, std::ios::binary | std::ios::trunc);
        file.write(static_cast<const char*>(data), static_cast<std::streamsize>(size));
        if (!file)
        {
            std::fprintf(stderr, "%s: error: cannot be written\n", path.generic_string().c_str());
            return false;
        }
        return true;
    }

    // A path in a Make-style depfile: spaces and '#' escaped with a backslash, '$' doubled.
    std::string DepfilePath(const fs::path& path)
    {
        std::string escaped;
        for (const char c : fs::absolute(path).lexically_normal().generic_string())
        {
            if (c == ' ' || c == '#')
            {
                escaped += '\\';
            }
            else if (c == '$')
            {
                escaped += '$';
            }
            escaped += c;
        }
        return escaped;
    }

    // The container as a byte array in a header, so the engine's own shaders run with no files beside them.
    std::string Header(const std::string& name, const std::vector<std::byte>& bytes)
    {
        std::string text = "// Generated by FenrirShaderCompiler from the shader program '" + name +
                           "'. Do not edit.\n#pragma once\n\n#include <cstdint>\n\nnamespace Fenrir::Shaders\n{\n"
                           "    /** @brief The shader container of the program '" +
                           name +
                           "', as FenrirShaderCompiler wrote it. */\n    alignas(4) inline constexpr std::uint8_t " +
                           name + "[] = {";
        for (std::size_t i = 0; i < bytes.size(); ++i)
        {
            text += i % 20 == 0 ? "\n        " : " ";
            text += std::to_string(std::to_integer<unsigned>(bytes[i])) + ",";
        }
        text += "\n    };\n} // namespace Fenrir::Shaders\n";
        return text;
    }
} // namespace

int main(int argc, char** argv)
{
    using namespace Fenrir::ShaderCompiler;
    std::vector<std::string> given;
    {
        // The one place the C-style argument array is walked.
#if defined(__clang__)
#pragma clang diagnostic push
#pragma clang diagnostic ignored "-Wunsafe-buffer-usage"
#endif
        given.assign(argv + 1, argv + argc);
#if defined(__clang__)
#pragma clang diagnostic pop
#endif
    }
    const std::optional<Arguments> arguments = ParseArguments(given);
    if (!arguments)
    {
        return 2;
    }

    Diagnostics diagnostics;
    std::set<fs::path> read;
    const std::optional<Fenrir::ShaderContainer> container = BuildProgram(arguments->program, read, diagnostics);
    if (!container)
    {
        return 1;
    }

    const std::vector<std::byte> bytes = Fenrir::WriteShaderContainer(*container);
    if (!WriteFile(arguments->output, bytes.data(), bytes.size()))
    {
        return 1;
    }
    if (!arguments->header.empty())
    {
        const std::string header = Header(arguments->program.name, bytes);
        if (!WriteFile(arguments->header, header.data(), header.size()))
        {
            return 1;
        }
    }
    if (!arguments->depfile.empty())
    {
        std::string depfile = DepfilePath(arguments->output) + ":";
        for (const fs::path& path : read)
        {
            depfile += " \\\n  " + DepfilePath(path);
        }
        depfile += "\n";
        if (!WriteFile(arguments->depfile, depfile.data(), depfile.size()))
        {
            return 1;
        }
    }
    return 0;
}
