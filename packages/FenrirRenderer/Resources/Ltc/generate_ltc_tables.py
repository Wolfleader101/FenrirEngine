"""Writes src/Core/LtcTables.hpp: the two 64 x 64 RGBA16F lookup tables of linearly transformed cosines for GGX
(Heitz, Dupuy, Hill and Neubelt 2016) that rect lights are shaded with (ADR-0048).

The tables are the reference fit's own, fit/results/ltc_1.dds and ltc_2.dds of github.com/selfshadow/ltc_code at a
pinned commit, checked against their SHA-256 and copied texel for texel as half floats. Their licence is LICENSE.txt
beside this script. The build never runs it:

    python packages/FenrirRenderer/Resources/Ltc/generate_ltc_tables.py [directory holding both .dds files]
"""

import hashlib
import pathlib
import struct
import sys
import urllib.request

COMMIT = "5c0770b74114b5dd38e9dae1b93f8486af7eac1b"
SOURCE = f"https://raw.githubusercontent.com/selfshadow/ltc_code/{COMMIT}/fit/results/"
TABLES = [
    ("ltc_1.dds", "6aa389c6c0403a408cf6bb23dcdc543ad3e97f0fdc49e60f034b6a85682ee18d", "LtcMatrixTexels"),
    ("ltc_2.dds", "2ff4f03b10d73e25985216d73a58aa57375f0c775dee0e1bde075d44e2b07200", "LtcAmplitudeTexels"),
]
SIDE = 64
# A DDS file's magic and header, whose four-character code names RGBA16F (113, D3DFMT_A16B16G16R16F).
HEADER_BYTES = 4 + 124
TEXEL_BYTES = 8
VALUES_PER_LINE = 12

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "src" / "Core" / "LtcTables.hpp"


def read_table(name, sha256, directory):
    data = (directory / name).read_bytes() if directory else urllib.request.urlopen(SOURCE + name).read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != sha256:
        sys.exit(f"{name}: SHA-256 {digest}, expected {sha256}")
    texels = data[len(data) - SIDE * SIDE * TEXEL_BYTES :]
    if len(data) != HEADER_BYTES + len(texels):
        sys.exit(f"{name}: {len(data)} bytes, expected a {HEADER_BYTES}-byte header and {SIDE} x {SIDE} RGBA16F")
    return struct.unpack(f"<{SIDE * SIDE * 4}H", texels)


def main():
    # A directory already holding both files, when downloading them here is not possible.
    directory = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else None
    lines = [
        "#pragma once",
        "",
        "// Generated by packages/FenrirRenderer/Resources/Ltc/generate_ltc_tables.py: do not edit.",
        "//",
        "// The linearly transformed cosines of GGX (Heitz, Dupuy, Hill and Neubelt 2016), from",
        f"// github.com/selfshadow/ltc_code at {COMMIT},",
        "// fit/results/ltc_1.dds and ltc_2.dds: 64 x 64 RGBA16F texels, row by row, perceptual roughness across and",
        "// sqrt(1 - N.V) down. Copyright (c) 2017, Eric Heitz, Jonathan Dupuy, Stephen Hill and David Neubelt; their",
        "// BSD-style licence is packages/FenrirRenderer/Resources/Ltc/LICENSE.txt.",
        "",
        "#include <array>",
        "#include <cstdint>",
        "",
        "namespace Fenrir::Render::Generated",
        "{",
        "    // clang-format off",
    ]
    comments = {
        "LtcMatrixTexels": "The inverse matrix's four varying entries, normalised by its middle one: m00, m02, m20, m22.",
        "LtcAmplitudeTexels": "The fit's GGX norm and Fresnel term, 0, and the horizon-clipped sphere's form factor.",
    }
    for name, sha256, symbol in TABLES:
        values = read_table(name, sha256, directory)
        lines.append(f"    /** @brief {comments[symbol]} */")
        lines.append(f"    inline constexpr std::array<std::uint16_t, {len(values)}> {symbol}{{")
        for start in range(0, len(values), VALUES_PER_LINE):
            chunk = values[start : start + VALUES_PER_LINE]
            lines.append("        " + " ".join(f"0x{value:04x}," for value in chunk))
        lines.append("    };")
    lines += ["    // clang-format on", "} // namespace Fenrir::Render::Generated", ""]
    # Binary, so the file keeps LF line endings on Windows too.
    OUTPUT.write_bytes("\n".join(lines).encode("ascii"))


if __name__ == "__main__":
    main()
