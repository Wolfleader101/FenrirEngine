using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Fenrir.Scripting.Generators;

/// <summary>
/// Finds the events a script assembly defines (structs implementing <c>IEvent</c> that do not mirror a C++ event) and writes
/// <c>Fenrir.Scripting.Generated.EventTable</c>, which reports each to the engine as the assembly loads. So an event needs no
/// C++ at all.
/// </summary>
[Generator]
public sealed class EventGenerator : IIncrementalGenerator
{
    private const string EventInterface = "Fenrir.Scripting.IEvent";
    private const string NativeEventAttribute = "Fenrir.Scripting.NativeEventAttribute";

    private static readonly DiagnosticDescriptor CannotStore = new(
        "FENRIR0014", "An event cannot be stored by the engine",
        "Event '{0}' must be a non-generic unmanaged struct that is not nested in a private or protected type",
        "Fenrir.Scripting", DiagnosticSeverity.Error, isEnabledByDefault: true);

    // What one event contributes. Plain data, so an unchanged event is not regenerated.
    private sealed record Model(string TypeName, string DisplayName, string? Entry, string Path, Microsoft.CodeAnalysis.Text.TextSpan Span,
        Microsoft.CodeAnalysis.Text.LinePositionSpan LineSpan);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValuesProvider<Model> events = context.SyntaxProvider
            .CreateSyntaxProvider(
                static (node, _) => node is StructDeclarationSyntax,
                static (syntax, cancellation) => Describe(syntax, cancellation))
            .Where(static model => model is not null)!;

        context.RegisterSourceOutput(events.Collect(), static (output, models) =>
        {
            var entries = new List<string>();
            foreach (Model model in models)
            {
                if (model.Entry == null)
                {
                    var location = Location.Create(model.Path, model.Span, model.LineSpan);
                    output.ReportDiagnostic(Diagnostic.Create(CannotStore, location, model.DisplayName));
                }
                else
                {
                    entries.Add(model.Entry);
                }
            }
            if (entries.Count == 0)
                return;
            var table = new StringBuilder();
            table.Append("// <auto-generated>Fenrir.Scripting.Generators: the events this script assembly defines.</auto-generated>\n");
            table.Append("namespace Fenrir.Scripting.Generated\n{\n    public static class EventTable\n    {\n");
            table.Append("        public static void Register()\n        {\n");
            foreach (string entry in entries.Distinct().OrderBy(static entry => entry, StringComparer.Ordinal))
                table.Append("            global::Fenrir.Scripting.ScriptEvents.Report<").Append(entry).Append(">();\n");
            table.Append("        }\n    }\n}\n");
            output.AddSource("Fenrir.Scripting.Generated.EventTable.g.cs", table.ToString());
        });
    }

    private static Model? Describe(GeneratorSyntaxContext context, System.Threading.CancellationToken cancellation)
    {
        var declaration = (StructDeclarationSyntax)context.Node;
        if (context.SemanticModel.GetDeclaredSymbol(declaration, cancellation) is not INamedTypeSymbol symbol)
            return null;
        if (!symbol.AllInterfaces.Any(static i => i.ToDisplayString() == EventInterface))
            return null;
        // A partial struct is seen once per declaration; only the first one counts.
        if (symbol.DeclaringSyntaxReferences[0].GetSyntax(cancellation) != declaration)
            return null;
        // A struct mirroring a C++ event is registered by the host, not by the script.
        bool isNative = symbol.GetAttributes().Any(static attribute => attribute.AttributeClass?.ToDisplayString() == NativeEventAttribute);

        Location at = declaration.Identifier.GetLocation();
        bool storable = !symbol.IsGenericType && symbol.IsUnmanagedType && !HasHiddenContainer(symbol);
        string fullName = symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        string? entry = storable ? (isNative ? "" : fullName) : null;
        if (entry == "")
            return null;
        return new Model(fullName, symbol.ToDisplayString(), entry, at.SourceTree?.FilePath ?? "", at.SourceSpan, at.GetLineSpan().Span);
    }

    private static bool HasHiddenContainer(INamedTypeSymbol symbol)
    {
        for (INamedTypeSymbol? current = symbol; current != null; current = current.ContainingType)
            if (current.DeclaredAccessibility is Accessibility.Private or Accessibility.Protected or Accessibility.ProtectedAndInternal)
                return true;
        return false;
    }
}
