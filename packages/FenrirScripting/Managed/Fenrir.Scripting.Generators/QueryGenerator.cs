using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;

namespace Fenrir.Scripting.Generators;

/// <summary>
/// Writes the query types of arity 1 to 8 into the Fenrir.Scripting contract itself (the generator runs on every compilation,
/// and does nothing for any other assembly): <c>World.Query&lt;A, B&gt;()</c>, the rows it yields, and the delegate that
/// <c>ForEach</c> takes. They cannot be written as one generic type, because each arity has its own row shape.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class QueryGenerator : IIncrementalGenerator
{
    private const int MaxArity = 8;
    private const string ContractAssembly = "Fenrir.Scripting";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterSourceOutput(context.CompilationProvider, static (output, compilation) =>
        {
            if (compilation.AssemblyName != ContractAssembly)
                return;
            output.AddSource("Fenrir.Scripting.Queries.g.cs", Build());
        });
    }

    private static string Build()
    {
        var text = new StringBuilder();
        text.Append("// <auto-generated>Fenrir.Scripting.Generators: queries of 1 to ").Append(MaxArity).Append(" components.</auto-generated>\n");
        text.Append("#nullable enable\nnamespace Fenrir.Scripting\n{\n");

        for (int arity = 1; arity <= MaxArity; arity++)
            AppendArity(text, arity);

        text.Append("    /// <summary>Where queries start.</summary>\n    public static partial class World\n    {\n");
        for (int arity = 1; arity <= MaxArity; arity++)
        {
            text.Append("        /// <summary>Every entity that has all of these components, read-write.</summary>\n");
            text.Append("        public static Query<").Append(Names(arity)).Append("> Query<").Append(Names(arity)).Append(">()");
            text.Append(Constraints(arity)).Append(" => default;\n");
        }
        text.Append("    }\n\n");

        // The same entry points on the context a system is given.
        text.Append("    public readonly partial struct SystemContext\n    {\n");
        for (int arity = 1; arity <= MaxArity; arity++)
        {
            text.Append("        /// <summary>Every entity that has all of these components, read-write.</summary>\n");
            text.Append("        public Query<").Append(Names(arity)).Append("> Query<").Append(Names(arity)).Append(">()");
            text.Append(Constraints(arity)).Append(" => default;\n");
        }
        text.Append("    }\n}\n");
        return text.ToString();
    }

    // Where component i (1-based) sits in a row: after the entity's words.
    private static string ComponentIndex(int i) => i == 1 ? "QueryNative.EntityWords" : "QueryNative.EntityWords + " + (i - 1);

    private static string Names(int arity) => string.Join(", ", Enumerable.Range(1, arity).Select(static i => "T" + i));

    private static string Constraints(int arity) =>
        string.Concat(Enumerable.Range(1, arity).Select(static i => $" where T{i} : unmanaged, IComponent"));

    private static void AppendArity(StringBuilder text, int arity)
    {
        string names = Names(arity);
        string constraints = Constraints(arity);
        // A row is the entity (QueryNative.EntityWords words: a C++ Fenrir::Entity, which C# reads whole) and a pointer
        // per component, so component i (1-based) is at EntityWords + i - 1.
        string stride = "(" + arity + " + QueryNative.EntityWords)";
        IEnumerable<int> each = Enumerable.Range(1, arity);

        // The delegate ForEach takes (a ref struct cannot be a type argument of Action<>, on every runtime we target).
        text.Append("    /// <summary>The body of a query's ForEach.</summary>\n");
        text.Append("    public delegate void QueryAction<").Append(names).Append(">(Entity entity, ")
            .Append(string.Join(", ", each.Select(static i => $"Ref<T{i}> component{i}"))).Append(')').Append(constraints).Append(";\n\n");

        // One row: the entity and a Ref to each component, which deconstructs.
        text.Append("    /// <summary>One entity a query visited, and its components.</summary>\n");
        text.Append("    public readonly unsafe ref struct QueryRow<").Append(names).Append(">").Append(constraints).Append("\n    {\n");
        text.Append("        private readonly nuint* row;\n");
        text.Append("        internal QueryRow(nuint* row) => this.row = row;\n");
        text.Append("        /// <summary>The entity, with its scene set as C++ holds it.</summary>\n        public Entity Entity => *(Entity*)row;\n");
        foreach (int i in each)
            text.Append($"        /// <summary>The entity's T{i}.</summary>\n        public Ref<T{i}> Component{i} => new((T{i}*)row[{ComponentIndex(i)}]);\n");
        text.Append("        public void Deconstruct(out Entity entity, ")
            .Append(string.Join(", ", each.Select(static i => $"out Ref<T{i}> component{i}"))).Append(")\n        {\n");
        text.Append("            entity = Entity;\n");
        foreach (int i in each)
            text.Append($"            component{i} = Component{i};\n");
        text.Append("        }\n    }\n\n");

        // The enumerator foreach uses. It owns the rows, and Dispose gives them back.
        text.Append("    /// <summary>Walks a query's rows. Dispose it (foreach does) to release them.</summary>\n");
        text.Append("    public unsafe ref struct QueryEnumerator<").Append(names).Append(">").Append(constraints).Append("\n    {\n");
        text.Append("        private nuint* rows;\n        private readonly int count;\n        private int index;\n");
        text.Append("        internal QueryEnumerator(nuint* rows, int count)\n        {\n            this.rows = rows;\n            this.count = count;\n            index = -1;\n        }\n");
        text.Append("        public QueryRow<").Append(names).Append("> Current => rows != null && index >= 0 && index < count\n");
        text.Append("            ? new(rows + (long)index * ").Append(stride).Append(")\n");
        text.Append("            : throw new InvalidOperationException(\"The query has no current row: call MoveNext first, and do not use it after Dispose.\");\n");
        text.Append("        public bool MoveNext() => ++index < count;\n");
        text.Append("        public void Dispose()\n        {\n            QueryNative.Release(rows);\n            rows = null;\n        }\n    }\n\n");

        // The query itself. It holds nothing: the rows are fetched when iteration starts.
        text.Append("    /// <summary>\n    /// Every entity with all of ").Append(names).Append(", found when iteration starts. Structural changes made while it runs are\n");
        text.Append("    /// deferred, so the rows stay valid. Use <c>foreach (var (entity, ...) in query)</c> or <see cref=\"ForEach\"/>.\n    /// </summary>\n");
        text.Append("    public readonly unsafe struct Query<").Append(names).Append(">").Append(constraints).Append("\n    {\n");
        text.Append("        public QueryEnumerator<").Append(names).Append("> GetEnumerator()\n        {\n");
        AppendFill(text, arity);
        text.Append("            return new QueryEnumerator<").Append(names).Append(">(rows, count);\n        }\n\n");
        text.Append("        /// <summary>Calls <paramref name=\"action\"/> for each entity.</summary>\n");
        text.Append("        public void ForEach(QueryAction<").Append(names).Append("> action)\n        {\n");
        AppendFill(text, arity);
        text.Append("            try\n            {\n                for (int index = 0; index < count; index++)\n                {\n");
        text.Append("                    nuint* row = rows + (long)index * ").Append(stride).Append(";\n");
        text.Append("                    action(*(Entity*)row, ")
            .Append(string.Join(", ", each.Select(static i => $"new Ref<T{i}>((T{i}*)row[{ComponentIndex(i)}])"))).Append(");\n");
        text.Append("                }\n            }\n            finally\n            {\n                QueryNative.Release(rows);\n            }\n        }\n    }\n\n");
    }

    private static void AppendFill(StringBuilder text, int arity)
    {
        text.Append("            int* ids = stackalloc int[").Append(arity).Append("];\n");
        for (int i = 1; i <= arity; i++)
            text.Append($"            ids[{i - 1}] = Entity.IdOf<T{i}>();\n");
        text.Append("            nuint* rows = QueryNative.Fill(ids, ").Append(arity).Append(", out int count);\n");
    }
}
